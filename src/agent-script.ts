/**
 * The remote-side op script: runs ONCE PER SSH INVOCATION (one JSON request on
 * stdin, EOF-closed — required for reliable Windows OpenSSH delivery — one JSON
 * response out). Failures come back as a `__error` hashtable, not exception
 * text. Written for Windows PowerShell 5.1: no `??`, no ternary, no `&&`/`||`.
 * Editing the string array changes the pinned SHA-256 in the tests.
 *
 * @module dsh-ssh/agent-script
 */

export const AGENT_SCRIPT = [
	'$ErrorActionPreference = \'Stop\'',
	'',
	'try {',
	'  [Console]::InputEncoding  = New-Object System.Text.UTF8Encoding($false, $true)',
	'  [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false)',
	'} catch { }',
	'',
	'function Write-Line([string]$text) {',
	'  [Console]::Out.WriteLine($text)',
	'  [Console]::Out.Flush()',
	'}',
	'',
	'function Fail([string]$code, [string]$message) {',
	'  return @{ __error = @{ code = $code; message = $message } }',
	'}',
	'',
	'function Get-EntryType($item) {',
	'  if ($item.PSIsContainer) { return \'directory\' }',
	'  if (($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -ne 0) { return \'symlink\' }',
	'  return \'file\'',
	'}',
	'',
	'function Get-EntryVersion($item) {',
	'  return [string]$item.LastWriteTimeUtc.Ticks + \':\' + [string]$item.Length',
	'}',
	'',
	'function Get-StatResult([string]$path) {',
	'  if (-not (Test-Path -LiteralPath $path)) { return @{ exists = $false } }',
	'  $item = Get-Item -LiteralPath $path -Force',
	'  return @{ exists = $true; type = (Get-EntryType $item); size = [int64]$item.Length; version = (Get-EntryVersion $item) }',
	'}',
	'',
	'function Get-ListResult([string]$path) {',
	'  if (-not (Test-Path -LiteralPath $path)) { return @{ exists = $false; items = @() } }',
	'  $items = @()',
	'  foreach ($item in Get-ChildItem -LiteralPath $path -Force) {',
	'    $items += @{ name = $item.Name; type = (Get-EntryType $item); size = [int64]$item.Length; version = (Get-EntryVersion $item) }',
	'  }',
	'  return @{ exists = $true; items = $items }',
	'}',
	'',
	'function Get-ReadResult([string]$path) {',
	'  if (-not (Test-Path -LiteralPath $path)) { return (Fail \'FS_NOT_FOUND\' (\'no such file: \' + $path)) }',
	'  $bytes = [System.IO.File]::ReadAllBytes($path)',
	'  return @{ size = [int64]$bytes.Length; base64 = [System.Convert]::ToBase64String($bytes) }',
	'}',
	'',
	'function Get-RangeResult([string]$path, [int64]$offset, [int64]$length) {',
	'  if (-not (Test-Path -LiteralPath $path)) { return (Fail \'FS_NOT_FOUND\' (\'no such file: \' + $path)) }',
	'  $fs = [System.IO.File]::Open($path, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::ReadWrite)',
	'  try {',
	'    if ($offset -lt 0) { $offset = 0 }',
	'    if ($offset -gt $fs.Length) { $offset = $fs.Length }',
	'    [void]$fs.Seek($offset, [System.IO.SeekOrigin]::Begin)',
	'    $take = $length',
	'    if ($take -lt 0 -or ($offset + $take) -gt $fs.Length) { $take = $fs.Length - $offset }',
	'    $buf = New-Object byte[] ([int]$take)',
	'    $read = 0',
	'    while ($read -lt $take) {',
	'      $n = $fs.Read($buf, $read, ([int]$take - $read))',
	'      if ($n -le 0) { break }',
	'      $read = $read + $n',
	'    }',
	'    if ($read -lt $take) {',
	'      if ($read -eq 0) { $buf = New-Object byte[] 0 } else { $buf = $buf[0..($read - 1)] }',
	'    }',
	'    return @{ size = [int64]$fs.Length; base64 = [System.Convert]::ToBase64String($buf) }',
	'  } finally { $fs.Dispose() }',
	'}',
	'',
	'function Write-BytesAtomic([string]$path, [byte[]]$bytes) {',
	'  $dir = [System.IO.Path]::GetDirectoryName($path)',
	'  if ($dir -and -not [System.IO.Directory]::Exists($dir)) { [void][System.IO.Directory]::CreateDirectory($dir) }',
	'  $tmp = [System.IO.Path]::Combine($dir, (\'.dsh-tmp-\' + [Guid]::NewGuid().ToString(\'N\')))',
	'  try {',
	'    [System.IO.File]::WriteAllBytes($tmp, $bytes)',
	'    if ([System.IO.File]::Exists($path)) {',
	'      try { [System.IO.File]::Replace($tmp, $path, $null) }',
	'      catch { [System.IO.File]::Delete($path); [System.IO.File]::Move($tmp, $path) }',
	'    } else {',
	'      [System.IO.File]::Move($tmp, $path)',
	'    }',
	'  } finally {',
	'    if ([System.IO.File]::Exists($tmp)) { [System.IO.File]::Delete($tmp) }',
	'  }',
	'}',
	'',
	'function Write-BytesResult([string]$path, [string]$base64, $expected) {',
	'  $existing = $null',
	'  if ([System.IO.File]::Exists($path)) { $existing = Get-Item -LiteralPath $path -Force }',
	'  if ($null -ne $expected) {',
	'    $kind = [string]$expected.kind',
	'    if ($kind -eq \'replaceIfVersion\') {',
	'      if ($null -eq $existing) { return (Fail \'FS_STALE_VERSION\' (\'file no longer exists: \' + $path)) }',
	'      if ((Get-EntryVersion $existing) -ne [string]$expected.version) {',
	'        return (Fail \'FS_STALE_VERSION\' (\'file changed since it was read: \' + $path))',
	'      }',
	'    } elseif ($kind -eq \'createIfAbsent\' -and $null -ne $existing) {',
	'      return (Fail \'FS_NOT_OBSERVED\' (\'cannot overwrite existing file without reading it first: \' + $path))',
	'    }',
	'  }',
	'  $bytes = [System.Convert]::FromBase64String($base64)',
	'  Write-BytesAtomic $path $bytes',
	'  $after = Get-Item -LiteralPath $path -Force',
	'  return @{ version = (Get-EntryVersion $after); existed = ($null -ne $existing) }',
	'}',
	'',
	'function Append-BytesResult([string]$path, [string]$base64) {',
'  $dir = [System.IO.Path]::GetDirectoryName($path)',
'  if ($dir -and -not [System.IO.Directory]::Exists($dir)) { [void][System.IO.Directory]::CreateDirectory($dir) }',
'  $bytes = [System.Convert]::FromBase64String($base64)',
'  $fs = New-Object System.IO.FileStream($path, [System.IO.FileMode]::Append, [System.IO.FileAccess]::Write)',
'  try { $fs.Write($bytes, 0, $bytes.Length) } finally { $fs.Dispose() }',
'  $after = Get-Item -LiteralPath $path -Force',
'  return @{ size = [int64]$after.Length; version = (Get-EntryVersion $after) }',
'}',
'',
'function Remove-PathResult([string]$path) {',
'  if ([System.IO.File]::Exists($path)) { [System.IO.File]::Delete($path) }',
'  return @{}',
'}',
'',
'function Get-WhereResult([string]$name, [string]$searchPath, [string]$pathExt) {',
'  $candidates = @($name)',
'  if (([System.IO.Path]::GetExtension($name) -eq \'\') -and $pathExt) {',
'    foreach ($ext in ($pathExt -split \';\')) { if ($ext) { $candidates += ($name + $ext) } }',
'  }',
'  if ($searchPath) {',
'    foreach ($dir in ($searchPath -split \';\')) {',
'      if (-not $dir) { continue }',
'      foreach ($cand in $candidates) {',
'        $full = [System.IO.Path]::Combine($dir, $cand)',
'        if ([System.IO.File]::Exists($full)) { return @{ path = $full } }',
'      }',
'    }',
'    return @{ path = $null }',
'  }',
'  $cmd = Get-Command $name -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1',
'  if ($null -eq $cmd) { return @{ path = $null } }',
'  return @{ path = [string]$cmd.Source }',
'}',
	'',
	'function Get-SystemResult() {',
	'  $pwsh = Get-Command pwsh -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1',
	'  return @{',
	'    os          = [string][System.Environment]::OSVersion.VersionString',
	'    machine     = [string]$env:COMPUTERNAME',
	'    user        = [string]$env:USERNAME',
	'    home        = [string]$env:USERPROFILE',
	'    pwsh        = $(if ($null -ne $pwsh) { [string]$pwsh.Source } else { $null })',
	'    architecture = [string]$env:PROCESSOR_ARCHITECTURE',
	'    comspec      = [string]$env:ComSpec',
	'  }',
	'}',
	'',
	'function Get-HashResult([string]$path) {',
'  if (-not [System.IO.File]::Exists($path)) { return (Fail \'FS_NOT_FOUND\' (\'no such file: \' + $path)) }',
'  $bytes = [System.IO.File]::ReadAllBytes($path)',
'  $sha = [System.Security.Cryptography.SHA256]::Create()',
'  try {',
'    $digest = $sha.ComputeHash($bytes)',
'    $hex = -join ($digest | ForEach-Object { $_.ToString(\'x2\') })',
'    return @{ sha256 = $hex; size = [int64]$bytes.Length }',
'  } finally { $sha.Dispose() }',
'}',
'',
'function Move-IntoPlace([string]$source, [string]$target) {',
'  if ([System.IO.File]::Exists($target)) { [System.IO.File]::Delete($target) }',
'  [System.IO.File]::Move($source, $target)',
'  $after = Get-Item -LiteralPath $target -Force',
'  return @{ size = [int64]$after.Length }',
'}',
'',
'function Concat-FilesResult([string]$target, $sources) {',
'  $dir = [System.IO.Path]::GetDirectoryName($target)',
'  if ($dir -and -not [System.IO.Directory]::Exists($dir)) { [void][System.IO.Directory]::CreateDirectory($dir) }',
'  $out = New-Object System.IO.FileStream($target, [System.IO.FileMode]::Create, [System.IO.FileAccess]::Write)',
'  try {',
'    foreach ($src in $sources) {',
'      if (-not [System.IO.File]::Exists($src)) { return (Fail \'FS_NOT_FOUND\' (\'missing part: \' + $src)) }',
'      $in = New-Object System.IO.FileStream($src, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read)',
'      try { $in.CopyTo($out) } finally { $in.Dispose() }',
'    }',
'  } finally { $out.Dispose() }',
'  foreach ($src in $sources) { if ([System.IO.File]::Exists($src)) { [System.IO.File]::Delete($src) } }',
'  $after = Get-Item -LiteralPath $target -Force',
'  return @{ size = [int64]$after.Length }',
'}',
'',
'function Invoke-Op([string]$op, $p) {',
	'  switch ($op) {',
	'    \'ping\'    { return @{} }',
	'    \'system\'  { return (Get-SystemResult) }',
	'    \'stat\'    { return (Get-StatResult ([string]$p.path)) }',
	'    \'list\'    { return (Get-ListResult ([string]$p.path)) }',
	'    \'read\'    { return (Get-ReadResult ([string]$p.path)) }',
	'    \'range\'   { return (Get-RangeResult ([string]$p.path) ([int64]$p.offset) ([int64]$p.length)) }',
	'    \'write\'   { return (Write-BytesResult ([string]$p.path) ([string]$p.base64) $p.expected) }',
	'    \'append\'  { return (Append-BytesResult ([string]$p.path) ([string]$p.base64)) }',
	'    \'remove\'  { return (Remove-PathResult ([string]$p.path)) }',
'    \'hash\'    { return (Get-HashResult ([string]$p.path)) }',
'    \'move\'    { return (Move-IntoPlace ([string]$p.source) ([string]$p.target)) }',
'    \'concat\'  { return (Concat-FilesResult ([string]$p.target) $p.sources) }',
	'    \'where\'   { return (Get-WhereResult ([string]$p.name) ([string]$p.path) ([string]$p.pathExt)) }',
	'    \'mkdir\'   { [void][System.IO.Directory]::CreateDirectory([string]$p.path); return @{} }',
	'    default   { return (Fail \'FS_IO_ERROR\' (\'unknown op: \' + $op)) }',
	'  }',
	'}',
	'',
	'while ($true) {',
	'  $line = [Console]::In.ReadLine()',
	'  if ($null -eq $line) { break }',
	'  if ($line.Trim().Length -eq 0) { continue }',
	'  $id = $null',
	'  try {',
	'    $req = ConvertFrom-Json $line',
	'    $id = $req.id',
	'    $result = Invoke-Op ([string]$req.op) $req.payload',
	'    if ($null -ne $result -and $result.Contains(\'__error\')) {',
	'      Write-Line (ConvertTo-Json @{ id = $id; ok = $false; error = $result.__error } -Compress -Depth 8)',
	'    } else {',
	'      Write-Line (ConvertTo-Json @{ id = $id; ok = $true; result = $result } -Compress -Depth 8)',
	'    }',
	'  } catch {',
	'    Write-Line (ConvertTo-Json @{ id = $id; ok = $false; error = @{ code = \'FS_IO_ERROR\'; message = [string]$_.Exception.Message } } -Compress -Depth 8)',
	'  }',
	'}',
].join('\n')
